// Apply translations to all locale files
fs.readdirSync(localesPath).forEach(lang => {
  if (lang === 'en' || lang === 'hi' || lang.length !== 2) return;
  if (!fs.lstatSync(path.join(localesPath, lang)).isDirectory()) return;

  const filePath = path.join(localesPath, lang, 'translation.json');
  if (!fs.existsSync(filePath)) return;

  const data = JSON.parse(fs.readFileSync(filePath, 'utf8'));
  const updates = allTranslations[lang];

  if (!updates) {
    console.log(`⚠️  No translations defined for ${lang}, skipping.`);
    return;
  }

  let updatedCount = 0;
  for (const [key, value] of Object.entries(updates)) {
    if (data[key] !== value) {
      data[key] = value;
      updatedCount++;
    }
  }

  fs.writeFileSync(filePath, JSON.stringify(data, null, 2), 'utf8');
  console.log(`✅ ${lang}/translation.json — ${updatedCount} keys translated`);
});

console.log('\n🎉 All translation files updated successfully!');
