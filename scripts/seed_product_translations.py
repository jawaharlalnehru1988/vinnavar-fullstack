def main():
    print("Connecting to PostgreSQL database:", DB_CONFIG["dbname"])
    conn = psycopg2.connect(**DB_CONFIG)
    cur = conn.cursor()

    # 1. Update Categories
    print("\n--- Updating Category Translations ---")
    for cat_id, data in CATEGORIES_DATA.items():
        # Check category exists
        cur.execute("SELECT id, name FROM categories WHERE id = %s", (cat_id,))
        cat_row = cur.fetchone()
        if not cat_row:
            print(f"Warning: Category ID {cat_id} not found, skipping.")
            continue
        print(f"Updating Category [{cat_id}]: {cat_row[1]}")

        # Update Name Translations
        for lang, name in data["names"].items():
            cur.execute("DELETE FROM category_name_translations WHERE category_id = %s AND lang_code = %s", (cat_id, lang))
            cur.execute("INSERT INTO category_name_translations (category_id, lang_code, translated_name) VALUES (%s, %s, %s)", (cat_id, lang, name))

        # Update Description Translations
        for lang, desc in data["descriptions"].items():
            cur.execute("DELETE FROM category_desc_translations WHERE category_id = %s AND lang_code = %s", (cat_id, lang))
            cur.execute("INSERT INTO category_desc_translations (category_id, lang_code, translated_desc) VALUES (%s, %s, %s)", (cat_id, lang, desc))

    # 2. Update Products
    print("\n--- Updating Product Translations ---")
    for prod_id, data in PRODUCTS_DATA.items():
        # Check product exists
        cur.execute("SELECT id, name FROM products WHERE id = %s", (prod_id,))
        prod_row = cur.fetchone()
        if not prod_row:
            print(f"Warning: Product ID {prod_id} not found, skipping.")
            continue
        print(f"Updating Product [{prod_id}]: {prod_row[1]}")

        # Update Name Translations
        for lang, name in data["names"].items():
            cur.execute("DELETE FROM product_name_translations WHERE product_id = %s AND lang_code = %s", (prod_id, lang))
            cur.execute("INSERT INTO product_name_translations (product_id, lang_code, translated_name) VALUES (%s, %s, %s)", (prod_id, lang, name))

        # Update Description Translations
        for lang, desc in data["descriptions"].items():
            cur.execute("DELETE FROM product_desc_translations WHERE product_id = %s AND lang_code = %s", (prod_id, lang))
            cur.execute("INSERT INTO product_desc_translations (product_id, lang_code, translated_desc) VALUES (%s, %s, %s)", (prod_id, lang, desc))

    conn.commit()
    cur.close()
    conn.close()
    print("\n[SUCCESS] Successfully populated all category and product translations across 8 Indian languages!")

if __name__ == "__main__":
    main()
